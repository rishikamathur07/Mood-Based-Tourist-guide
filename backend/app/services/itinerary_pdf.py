"""Generate a compact, printable itinerary PDF for a saved trip."""

from io import BytesIO

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from app.services.currency import format_money
from algorithms.scheduler import format_duration, format_minutes


def build_itinerary_pdf(trip, local_budget: dict, currency: str) -> bytes:
    """Return a traveller-friendly PDF without depending on browser printing."""
    output = BytesIO()
    document = SimpleDocTemplate(
        output,
        pagesize=A4,
        rightMargin=1.6 * cm,
        leftMargin=1.6 * cm,
        topMargin=1.5 * cm,
        bottomMargin=1.5 * cm,
        title=f"Mood itinerary - {trip.city}",
    )
    styles = getSampleStyleSheet()
    title = styles["Title"]
    title.textColor = colors.HexColor("#0d2621")
    heading = styles["Heading2"]
    heading.textColor = colors.HexColor("#16433a")
    body = styles["BodyText"]
    body.leading = 15

    story = [
        Paragraph("MOOD", styles["Heading3"]),
        Paragraph(f"{trip.city} itinerary", title),
        Paragraph(
            f"{trip.num_days} day(s) | {trip.num_people} traveller(s) | "
            f"{trip.mood.title()} | {trip.budget_level} budget",
            body,
        ),
        Spacer(1, 0.45 * cm),
        Paragraph("Your day-by-day plan", heading),
    ]

    rows = [["Day", "Time", "Place", "Details"]]
    for stop in trip.itinerary_stops:
        place = stop.place
        rows.append([
            f"Day {stop.day}",
            f"{format_minutes(stop.start_minutes)} - {format_minutes(stop.end_minutes)}",
            place.name,
            f"{place.category}; {format_duration(place.avg_time_spent_mins)}; {format_money(place.avg_cost, currency)}",
        ])
    table = Table(rows, colWidths=[1.2 * cm, 3.4 * cm, 6.0 * cm, 6.1 * cm], repeatRows=1)
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#16433a")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 8.5),
        ("LEADING", (0, 0), (-1, -1), 11),
        ("GRID", (0, 0), (-1, -1), 0.35, colors.HexColor("#d2cbbe")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#f6f3eb")]),
        ("TOPPADDING", (0, 0), (-1, -1), 7),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 7),
    ]))
    story.extend([table, Spacer(1, 0.45 * cm), Paragraph("Estimated local trip cost", heading)])
    cost_rows = [
        ["Attractions", format_money(local_budget["attractions"], currency)],
        ["Stay", format_money(local_budget["stay"], currency)],
        ["Meals", format_money(local_budget["food"], currency)],
        ["Local transport", format_money(local_budget["transport"], currency)],
        ["Estimated total", format_money(local_budget["total"], currency)],
    ]
    cost_table = Table(cost_rows, colWidths=[8.5 * cm, 4.0 * cm])
    cost_table.setStyle(TableStyle([
        ("BACKGROUND", (0, -1), (-1, -1), colors.HexColor("#eaf1ec")),
        ("FONTNAME", (0, -1), (-1, -1), "Helvetica-Bold"),
        ("GRID", (0, 0), (-1, -1), 0.35, colors.HexColor("#d2cbbe")),
        ("ALIGN", (1, 0), (1, -1), "RIGHT"),
        ("TOPPADDING", (0, 0), (-1, -1), 7),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 7),
    ]))
    story.extend([
        cost_table,
        Spacer(1, 0.35 * cm),
        Paragraph("Flights are not included because live fares depend on route and booking date.", body),
        Paragraph("Generated by Mood - your mood-based travel planner.", body),
    ])
    document.build(story)
    return output.getvalue()
